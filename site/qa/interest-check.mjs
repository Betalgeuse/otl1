import assert from 'node:assert/strict';

const site = 'http://localhost:8791';
const core = 'http://localhost:8790';
const results = [];
const request = (path, options = {}) => fetch(`${site}${path}`, { redirect: 'manual', ...options });
const form = (values) => new URLSearchParams(values);
const base = { email: `test-${crypto.randomUUID()}@example.test`, displayName: '테스트', intent: '함께 한 가지를 끝내고 싶습니다.', knownMemberClue: '', consent: 'interest-consent-v1', inviteConsent: 'invite-consent-v1', 'cf-turnstile-response': '1x00000000000000000000AA' };
const send = (values) => request('/interest', { method: 'POST', body: form(values) });
const check = (name, actual, expected) => { assert.equal(actual, expected, name); results.push({ scenario: name, observed: actual, expected }); };

const before = await (await fetch(`${core}/__qa/stats`)).json();
const page = await request('/interest');
check('enabled GET /interest', page.status, 200);
const html = await page.text();
assert.match(html, /data-action="interest-submit"/);
assert.match(html, /shareNameEmailWithIntroducer/);
const key = html.match(/name="submissionKey" value="([^"]+)"/)?.[1];
assert.ok(key);
const home = await (await request('/')).text();
assert.match(home, /href="\/interest"/);
results.push({ scenario: 'enabled homepage CTA', observed: 'linked' });
check('raw interest asset blocked', (await request('/interest.html')).status, 404);
check('missing admin consent', (await send({ ...base, submissionKey: crypto.randomUUID(), consent: '' })).status, 422);
check('missing invitation consent', (await send({ ...base, submissionKey: crypto.randomUUID(), inviteConsent: '' })).status, 422);
check('malformed email', (await send({ ...base, submissionKey: crypto.randomUUID(), email: 'invalid' })).status, 422);
check('oversized streaming body', (await send({ ...base, submissionKey: crypto.randomUUID(), intent: '가'.repeat(7000) })).status, 422);
const submitted = await send({ ...base, submissionKey: key, knownMemberClue: '확인되지 않은 회원' });
check('valid two-Worker intake', submitted.status, 303);
const location = submitted.headers.get('location');
assert.match(location ?? '', /^\/receipt\/INT-[A-Z0-9-]+$/);
const cookie = submitted.headers.get('set-cookie');
assert.match(cookie ?? '', /HttpOnly; Secure; SameSite=Strict/);
assert.ok(!cookie.includes(base.email) && !cookie.includes('테스트'));
const cookiePair = cookie.split(';')[0];
const receipt = await (await request(location, { headers: { cookie: cookiePair } })).text();
assert.match(receipt, /문의만으로 참여 자격이나 초대가 생기지 않으며/);
const withdrawalKey = receipt.match(/name="withdrawalKey" value="([^"]+)"/)?.[1];
assert.ok(withdrawalKey);
await new Promise((resolve) => setTimeout(resolve, 1200));
check('duplicate submit same key after wall-clock change', (await send({ ...base, submissionKey: key, knownMemberClue: '확인되지 않은 회원' })).status, 303);
check('same key with changed intent rejected', (await send({ ...base, submissionKey: key, intent: '다른 이유', knownMemberClue: '확인되지 않은 회원' })).status, 503);
const duplicateEmail = await send({ ...base, submissionKey: crypto.randomUUID() });
check('duplicate email under new key generic receipt', duplicateEmail.status, 303);
assert.equal(duplicateEmail.headers.get('set-cookie'), null);
assert.doesNotMatch(await (await request(duplicateEmail.headers.get('location'))).text(), /문의 철회 요청/);
results.push({ scenario: 'duplicate email has no capability or public state detail', observed: true });
const afterSubmit = await (await fetch(`${core}/__qa/stats`)).json();
check('one interest request created', afterSubmit.interestCreated - before.interestCreated, 1);
check('no referral created', afterSubmit.created - before.created, 0);
const withdrawalPath = `${location}/withdraw`;
check('malformed withdrawal preserves capability', (await request(withdrawalPath, { method: 'POST', headers: { cookie: cookiePair }, body: form({ withdrawalKey: 'short' }) })).status, 422);
check('withdraw capability', (await request(withdrawalPath, { method: 'POST', headers: { cookie: cookiePair }, body: form({ withdrawalKey }) })).status, 303);
check('idempotent repeat withdrawal', (await request(withdrawalPath, { method: 'POST', headers: { cookie: cookiePair }, body: form({ withdrawalKey }) })).status, 303);
const afterWithdraw = await (await fetch(`${core}/__qa/stats`)).json();
check('one withdrawal effect', afterWithdraw.interestWithdrawals - before.interestWithdrawals, 1);
check('unknown receipt generic withdrawal', (await request('/receipt/INT-UNKNOWN1234/withdraw', { method: 'POST', body: form({ withdrawalKey }) })).status, 404);
const lostKey = `qa-lost-response-${crypto.randomUUID()}`;
const lostInput = { ...base, email: `lost-${crypto.randomUUID()}@example.test`, submissionKey: lostKey };
check('lost first response after Core commit', (await send(lostInput)).status, 503);
const recovered = await send(lostInput);
check('same-key retry recovers receipt', recovered.status, 303);
assert.match(recovered.headers.get('set-cookie') ?? '', /HttpOnly/);
const lostReceipt = recovered.headers.get('location');
const lostCookie = recovered.headers.get('set-cookie').split(';')[0];
const lostHtml = await (await request(lostReceipt, { headers: { cookie: lostCookie } })).text();
const lostWithdrawalKey = lostHtml.match(/name="withdrawalKey" value="([^"]+)"/)?.[1];
assert.ok(lostWithdrawalKey);
check('recovered capability withdraws', (await request(`${lostReceipt}/withdraw`, { method: 'POST', headers: { cookie: lostCookie }, body: form({ withdrawalKey: lostWithdrawalKey }) })).status, 303);
const finalStats = await (await fetch(`${core}/__qa/stats`)).json();
check('lost response created one additional request', finalStats.interestCreated - before.interestCreated, 2);
check('lost response withdraws once', finalStats.interestWithdrawals - before.interestWithdrawals, 2);
check('unsigned Core path rejected', (await fetch(`${core}/internal/interest/submit`, { method: 'POST', body: '{}' })).status, 401);
console.log(JSON.stringify({ ok: true, results }, null, 2));
