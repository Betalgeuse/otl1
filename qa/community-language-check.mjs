import assert from 'node:assert/strict';
import { classifyCommunityIntent, parseCommunityInterpretation, generateEncouragement } from '../src/community-language.ts';
const input={goal:'논문 읽기',text:'다 했어요'};
const valid={intent:'completion',outcome:'complete',goalText:null,hasReflection:false,needsConfirmation:false};
assert.equal(parseCommunityInterpretation(valid,input).outcome,'complete');
assert.equal(parseCommunityInterpretation(valid,{...input,goal:null}).intent,'unclear');
const contradictory=parseCommunityInterpretation({...valid,hasReflection:true},input);
assert.equal(contradictory.intent,'reflection');
assert.equal(contradictory.needsConfirmation,true);
assert.equal(parseCommunityInterpretation({...valid,intent:'reflection',hasReflection:true,outcome:'unknown'},input).needsConfirmation,true);
assert.equal(parseCommunityInterpretation({...valid,hasReflection:true},{...input,text:'친구가 다 했어요'}).intent,'ignore');
assert.equal(parseCommunityInterpretation({...valid,hasReflection:true},{...input,text:'어제 다 했어요'}).intent,'unclear');
assert.equal(parseCommunityInterpretation({...valid,needsConfirmation:'false'},input).intent,'unclear');
assert.equal(parseCommunityInterpretation({...valid,intent:'goal',goalText:'invented'},{goal:null,text:'논문 읽기'}).intent,'unclear');
assert.equal((await classifyCommunityIntent({run:async()=>({response:'broken json'})},input)).intent,'unclear');
assert.equal((await classifyCommunityIntent({run:async()=>{throw new TypeError('unavailable')}},input)).needsConfirmation,true);
assert.equal((await classifyCommunityIntent({run:async()=>{throw new Error('Must not call')}},{goal:null,text:'x'.repeat(1001)})).intent,'unclear');
const encouragement=await generateEncouragement({run:async()=>({response:JSON.stringify({text:'<!channel> click https://bad.example'})})},{kind:'rest',text:'쉬기',userId:'synthetic'});
assert.ok(!encouragement.includes('<!channel>'));
assert.ok(!encouragement.includes('https://'));
console.log('14 boundary assertions passed');
